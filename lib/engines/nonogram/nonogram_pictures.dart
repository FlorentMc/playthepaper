/// The authored picture set, an exact copy of `content_src/nonogram/pictures.json`
/// so the generator needs no file access. A test keeps the two in step.
class NonogramPicture {
  const NonogramPicture({required this.title, required this.rows});

  final String title;

  /// One string per row, `1` for a filled cell.
  final List<String> rows;

  int get size => rows.length;

  static NonogramPicture fromJson(Map<String, dynamic> json) {
    final title = json['title'];
    final rows = json['rows'];
    if (title is! String || title.isEmpty) throw const FormatException('Picture is missing "title"');
    if (rows is! List || rows.isEmpty || rows.any((r) => r is! String)) {
      throw FormatException('Picture "$title" is missing "rows"');
    }
    final size = json['size'];
    if (size is int && size != rows.length) throw FormatException('Picture "$title" declares size $size with ${rows.length} rows');
    return NonogramPicture(title: title, rows: List<String>.unmodifiable(rows.cast<String>()));
  }

  Map<String, dynamic> toJson() => {'title': title, 'size': size, 'rows': List<String>.of(rows)};
}

